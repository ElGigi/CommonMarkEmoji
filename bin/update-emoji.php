/*
 * Regenerates src/Emoji.php and the emoji list of README.md from the GitHub gemoji database,
 * which provides the full Unicode sequences (including ZWJ and variation selectors).
 *
 * Usage: php bin/update-emoji.php [path or URL of emoji.json]
 */

declare(strict_types=1);

const GEMOJI_URL = 'https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json';

$rootDir = dirname(__DIR__);
$source = $argv[1] ?? GEMOJI_URL;

$json = file_get_contents($source);
if (false === $json) {
    fwrite(STDERR, sprintf('Unable to read "%s"' . PHP_EOL, $source));
    exit(1);
}

$codes = [];
foreach (json_decode($json, true, 512, JSON_THROW_ON_ERROR) as $entry) {
    foreach ($entry['aliases'] as $alias) {
        if (!preg_match('/^[a-z0-9_+\-]+$/', $alias)) {
            fwrite(STDERR, sprintf('Unexpected emoji code "%s"' . PHP_EOL, $alias));
            exit(1);
        }

        $codes[(string)$alias] = $entry['emoji'];
    }
}
ksort($codes, SORT_STRING);

// Emoji.php
$lines = [];
foreach ($codes as $alias => $emoji) {
    $codePoints = unpack('N*', iconv('UTF-8', 'UTF-32BE', $emoji));
    $lines[] = sprintf(
        '        "%s" => "%s",',
        $alias,
        implode('', array_map(fn(int $codePoint): string => sprintf('\u{%04x}', $codePoint), $codePoints))
    );
}

$php = <<<'PHP'
<?php
/*
 * @license   https://opensource.org/licenses/MIT MIT License
 * @copyright 2021 Ronan GIRON
 * @author    Ronan GIRON <https://github.com/ElGigi>
 *
 * For the full copyright and license information, please view the LICENSE
 * file that was distributed with this source code, to the root.
 */

declare(strict_types=1);

namespace ElGigi\CommonMarkEmoji;

/**
 * This file is generated by bin/update-emoji.php, do not edit it manually.
 */
final class Emoji
{
    public static array $codes = [
%s
    ];
}

PHP;
file_put_contents($rootDir . '/src/Emoji.php', sprintf($php, implode(PHP_EOL, $lines)));

// README.md
$readmeFile = $rootDir . '/README.md';
$readme = file_get_contents($readmeFile);
$heading = '## Emoji list';
$position = strpos($readme, $heading);
if (false === $position) {
    fwrite(STDERR, sprintf('Heading "%s" not found in README.md' . PHP_EOL, $heading));
    exit(1);
}

$table = [
    sprintf('| %-40s | %-38s |', 'Code', 'Emoji'),
    sprintf('|%s|%s|', str_repeat('-', 42), str_repeat('-', 40)),
];
foreach (array_keys($codes) as $alias) {
    $table[] = sprintf('| %-40s | %-38s |', sprintf('`:%s:`', $alias), sprintf(':%s:', $alias));
}

file_put_contents(
    $readmeFile,
    substr($readme, 0, $position) . $heading . PHP_EOL . PHP_EOL . implode(PHP_EOL, $table) . PHP_EOL
);

printf('%d emoji written.' . PHP_EOL, count($codes));
